# Wraps MLIR.IR.run! to capture diagnostics.
# On failure: throws CompilationError containing all diagnostics.
# On success: prints any non-remark diagnostics to stderr using the same format.
function run!(pm::MLIR.IR.PassManager, op, key::String="")
    diagnostics = DiagnosticMessage[]
    handler =
        MLIR.IR.attach_diagnostic_handler!(; context=MLIR.IR.current_context()) do diag
            severity = MLIR.IR.severity(diag)
            severity > DEBUG_MLIR_DIAGNOSTIC_LEVEL[] && return false
            push!(
                diagnostics,
                DiagnosticMessage(
                    severity,
                    _sprint_diagnostic(diag),
                    _collect_location_frames(MLIR.IR.location(diag)),
                ),
            )
            return true  # consume the diagnostic
        end
    result = try
        MLIR.IR.run!(pm, op, key)
    catch
        throw(CompilationError(key, diagnostics))
    finally
        MLIR.IR.detach_diagnostic_handler!(handler)
    end
    isempty(diagnostics) || _print_diagnostics(stderr, diagnostics)
    return result
end

# Frontend loop bounds may still be constant expressions before the optimizer
# sees them. Evaluate only scalar integer expressions with defined, nonoverflowing
# arithmetic; leave other values for the normal compiler pipeline. Share the
# memo table across the preservation traversal, including unrecognized values,
# so repeated SSA operands do not cause exponential work.
function constant_loop_limit(
    value, constants=Dict{MLIR.IR.Value,Any}(), depth=0; through_loop_limits=false
)
    depth < 64 || return nothing
    return get!(constants, value) do
        evaluate_constant_loop_limit(value, constants, depth, through_loop_limits)
    end
end

function evaluate_constant_loop_limit(value, constants, depth, through_loop_limits=false)
    MLIR.IR.is_op_res(value) || return nothing
    ty = MLIR.IR.type(value)
    MLIR.IR.isshaped(ty) && MLIR.IR.hasrank(ty) || return nothing
    size(ty) == () || return nothing
    element = eltype(ty)
    MLIR.IR.isinteger(element) || return nothing
    MLIR.IR.bitwidth(element) in (8, 16, 32, 64) || return nothing
    T = MLIR.IR.julia_type(element)
    owner = MLIR.IR.op_owner(value)
    name = MLIR.IR.name(owner)
    if through_loop_limits &&
        name == "stablehlo.optimization_barrier" &&
        MLIR.IR.getattr(owner, "reactant.loop_limit") !== nothing
        return constant_loop_limit(
            MLIR.IR.operand(owner, 1), constants, depth + 1; through_loop_limits
        )
    end
    if name == "stablehlo.constant"
        attribute = MLIR.IR.getattr(owner, "value")
        MLIR.API.mlirDenseElementsAttrIsSplat(attribute) || return nothing
        scalar = MLIR.API.mlirDenseElementsAttrGetSplatValue(attribute)
        return MLIR.API.mlirIntegerAttrGetValueInt(scalar) % T
    end
    name in (
        "stablehlo.add",
        "stablehlo.subtract",
        "stablehlo.multiply",
        "stablehlo.divide",
        "stablehlo.convert",
    ) || return nothing
    operands = map(MLIR.IR.operands(owner)) do operand
        constant_loop_limit(operand, constants, depth + 1; through_loop_limits)
    end
    any(isnothing, operands) && return nothing
    try
        result = if name == "stablehlo.convert"
            T(only(operands))
        elseif name == "stablehlo.add"
            Base.Checked.checked_add(operands...)
        elseif name == "stablehlo.subtract"
            Base.Checked.checked_sub(operands...)
        elseif name == "stablehlo.multiply"
            Base.Checked.checked_mul(operands...)
        else
            div(operands...)
        end
        return T(result)
    catch error
        error isa Union{OverflowError,DivideError,InexactError} || rethrow()
        return nothing
    end
end

function contains_lazy_branch(op)
    MLIR.IR.name(op) == "stablehlo.if" && return true
    for region in op, block in region, child in block
        contains_lazy_branch(child) && return true
    end
    return false
end

function loop_condition_at_state(compare, block, state)
    constants = Dict{MLIR.IR.Value,Any}(
        MLIR.IR.argument(block, i) => state[i] for i in eachindex(state)
    )
    values = map(MLIR.IR.operands(compare)) do value
        constant_loop_limit(value, constants; through_loop_limits=true)
    end
    length(values) == 2 && all(value -> value isa Signed, values) || return nothing
    typeof(values[1]) == typeof(values[2]) || return nothing
    compare_type = MLIR.IR.getattr(compare, "compare_type")
    if compare_type !== nothing
        kind = String(MLIR.API.stablehloComparisonTypeAttrGetValue(compare_type))
        kind in ("SIGNED", "NOTYPE") || return nothing
    end
    direction = String(
        MLIR.API.stablehloComparisonDirectionAttrGetValue(
            MLIR.IR.getattr(compare, "comparison_direction")
        ),
    )
    lhs, rhs = values
    direction == "LT" && return lhs < rhs
    direction == "LE" && return lhs <= rhs
    direction == "GT" && return lhs > rhs
    direction == "GE" && return lhs >= rhs
    direction == "EQ" && return lhs == rhs
    direction == "NE" && return lhs != rhs
    return nothing
end

# Prove entry and exit after one integer state update. A literal comparison
# bound of one is insufficient: countdowns and shifted/non-unit induction
# variables can use that bound for many iterations.
function is_singleton_loop(op)
    MLIR.IR.name(op) == "stablehlo.while" || return false
    condition = first(first(op))
    terminator = MLIR.IR.terminator(condition)
    MLIR.IR.noperands(terminator) == 1 || return false
    value = MLIR.IR.operand(terminator, 1)
    MLIR.IR.is_op_res(value) || return false
    compare = MLIR.IR.op_owner(value)
    MLIR.IR.name(compare) == "stablehlo.compare" || return false
    constants = Dict{MLIR.IR.Value,Any}()
    initial = map(MLIR.IR.operands(op)) do value
        constant_loop_limit(value, constants; through_loop_limits=true)
    end
    loop_condition_at_state(compare, condition, initial) === true || return false
    body = first(MLIR.IR.region(op, 2))
    updated_constants = Dict{MLIR.IR.Value,Any}(
        MLIR.IR.argument(body, i) => initial[i] for i in eachindex(initial)
    )
    updated = map(MLIR.IR.operands(MLIR.IR.terminator(body))) do value
        constant_loop_limit(value, updated_constants; through_loop_limits=true)
    end
    return loop_condition_at_state(compare, condition, updated) === false
end

# Use a state component that actually changes. An invariant integer bound can
# precede the induction variable in the carried tuple.
function singleton_loop_induction_variable(op)
    constants = Dict{MLIR.IR.Value,Any}()
    initial = map(MLIR.IR.operands(op)) do value
        constant_loop_limit(value, constants; through_loop_limits=true)
    end
    body = first(MLIR.IR.region(op, 2))
    updated_constants = Dict{MLIR.IR.Value,Any}(
        MLIR.IR.argument(body, i) => initial[i] for i in eachindex(initial)
    )
    for (i, value) in enumerate(MLIR.IR.operands(MLIR.IR.terminator(body)))
        initial[i] isa Signed || continue
        updated = constant_loop_limit(value, updated_constants; through_loop_limits=true)
        updated isa Signed && initial[i] != updated || continue
        return MLIR.IR.argument(body, i)
    end
    return nothing
end

# Enzyme's loop cache lowering uses a zero-based unit-step counter. For a
# proven single iteration, normalize the selected integer state to that
# counter while preserving its original value in the body and its original
# final result. Other condition operations still see the original entry/exit
# values. No data-dependent state or iteration count is changed.
function normalize_singleton_induction!(op, index)
    position = MLIR.IR.block_arg_num(index) + 1
    initial = constant_loop_limit(MLIR.IR.operand(op, position); through_loop_limits=true)
    body = first(MLIR.IR.region(op, 2))
    constants = Dict{MLIR.IR.Value,Any}(
        MLIR.IR.argument(body, i) => constant_loop_limit(value; through_loop_limits=true)
        for (i, value) in enumerate(MLIR.IR.operands(op))
    )
    updated = constant_loop_limit(
        MLIR.IR.operand(MLIR.IR.terminator(body), position),
        constants;
        through_loop_limits=true,
    )
    condition = first(first(op))
    compare = MLIR.IR.op_owner(MLIR.IR.operand(MLIR.IR.terminator(condition), 1))
    direction = String(
        MLIR.API.stablehloComparisonDirectionAttrGetValue(
            MLIR.IR.getattr(compare, "comparison_direction")
        ),
    )
    if initial == 0 &&
        updated == 1 &&
        direction == "LT" &&
        MLIR.IR.operand(compare, 1) == MLIR.IR.argument(condition, position) &&
        constant_loop_limit(MLIR.IR.operand(compare, 2); through_loop_limits=true) == 1
        return index
    end
    ty = MLIR.IR.type(index)
    parent = MLIR.IR.block(op)
    function integer_constant(value)
        constant = MLIR.IR.create_operation_common(
            "stablehlo.constant",
            MLIR.IR.location(op);
            results=[ty],
            operands=MLIR.IR.Value[],
            attributes=[
                MLIR.IR.NamedAttribute(
                    "value", fill(MLIR.IR.Attribute(value, eltype(ty)), ty)
                ),
            ],
            result_inference=false,
        )
        MLIR.IR.insert_before!(parent, op, constant)
        return MLIR.IR.result(constant, 1)
    end
    zero, one = integer_constant(0), integer_constant(1)
    entry, exit = integer_constant(initial), integer_constant(updated)
    MLIR.API.mlirValueReplaceAllUsesOfWith(index, entry)
    MLIR.API.mlirValueReplaceAllUsesOfWith(MLIR.IR.result(op, position), exit)
    MLIR.IR.setoperand!(op, position, zero)
    counter = MLIR.IR.argument(condition, position)
    anchor = first(condition)
    first_iteration = MLIR.IR.create_operation_common(
        "stablehlo.compare",
        MLIR.IR.location(op);
        results=[MLIR.IR.TensorType(Int[], MLIR.IR.Type(Bool))],
        operands=[counter, zero],
        attributes=[
            MLIR.IR.NamedAttribute(
                "comparison_direction",
                parse(MLIR.IR.Attribute, "#stablehlo<comparison_direction EQ>"),
            ),
        ],
        result_inference=false,
    )
    MLIR.IR.insert_before!(condition, anchor, first_iteration)
    original = MLIR.IR.create_operation_common(
        "stablehlo.select",
        MLIR.IR.location(op);
        results=[ty],
        operands=[MLIR.IR.result(first_iteration, 1), entry, exit],
        result_inference=false,
    )
    MLIR.IR.insert_before!(condition, anchor, original)
    MLIR.API.mlirValueReplaceAllUsesOfWith(counter, MLIR.IR.result(original, 1))
    MLIR.IR.setoperand!(first_iteration, 1, counter)
    more = MLIR.IR.create_operation_common(
        "stablehlo.compare",
        MLIR.IR.location(op);
        results=[MLIR.IR.TensorType(Int[], MLIR.IR.Type(Bool))],
        operands=[counter, one],
        attributes=[
            MLIR.IR.NamedAttribute(
                "comparison_direction",
                parse(MLIR.IR.Attribute, "#stablehlo<comparison_direction LT>"),
            ),
        ],
        result_inference=false,
    )
    MLIR.IR.insert_before!(condition, MLIR.IR.terminator(condition), more)
    MLIR.IR.setoperand!(MLIR.IR.terminator(condition), 1, MLIR.IR.result(more, 1))
    next = MLIR.IR.create_operation_common(
        "stablehlo.add",
        MLIR.IR.location(op);
        results=[ty],
        operands=[index, one],
        result_inference=false,
    )
    MLIR.IR.insert_before!(body, MLIR.IR.terminator(body), next)
    MLIR.IR.setoperand!(MLIR.IR.terminator(body), position, MLIR.IR.result(next, 1))
    return index
end

function depend_singleton_guards_on_induction!(block::MLIR.IR.Block, equality)
    for child in collect(block)
        if MLIR.IR.name(child) == "stablehlo.if"
            predicate = MLIR.IR.operand(child, 1)
            conjunction = MLIR.IR.create_operation_common(
                "stablehlo.and",
                MLIR.IR.location(child);
                results=[MLIR.IR.type(predicate)],
                operands=[predicate, equality],
                result_inference=false,
            )
            MLIR.IR.insert_before!(block, child, conjunction)
            MLIR.IR.setoperand!(child, 1, MLIR.IR.result(conjunction, 1))
        end
        for region in child, nested_block in region
            depend_singleton_guards_on_induction!(nested_block, equality)
        end
    end
    return nothing
end

# For singleton batches, slicing a one-element tensor removes the guard's
# dependence on the induction variable. LICM can then hoist the guard and erase
# the loop even with its bound sealed. Retain that dependence through an integer
# identity: i == optimization_barrier(i) is always true. Its integer operands
# are nondifferentiable, so ordinary AD requires no floating barrier adjoint.
function preserve_singleton_loop_predicates!(op)
    preserved = false
    for region in op, block in region, child in collect(block)
        preserved |= preserve_singleton_loop_predicates!(child)
    end
    MLIR.IR.name(op) == "stablehlo.while" || return preserved
    contains_lazy_branch(op) && is_singleton_loop(op) || return preserved
    MLIR.IR.getattr(op, "reactant.singleton_predicate") !== nothing && return true
    index = singleton_loop_induction_variable(op)
    index === nothing && return preserved
    index = normalize_singleton_induction!(op, index)
    body = first(MLIR.IR.region(op, 2))
    anchor = first(body)
    barrier = MLIR.IR.create_operation_common(
        "stablehlo.optimization_barrier",
        MLIR.IR.location(op);
        results=[MLIR.IR.type(index)],
        operands=[index],
        result_inference=false,
    )
    MLIR.IR.insert_before!(body, anchor, barrier)
    equality = MLIR.IR.create_operation_common(
        "stablehlo.compare",
        MLIR.IR.location(op);
        results=[MLIR.IR.TensorType(Int[], MLIR.IR.Type(Bool))],
        operands=[index, MLIR.IR.result(barrier, 1)],
        attributes=[
            MLIR.IR.NamedAttribute(
                "comparison_direction",
                parse(MLIR.IR.Attribute, "#stablehlo<comparison_direction EQ>"),
            ),
        ],
        result_inference=false,
    )
    MLIR.IR.insert_before!(body, anchor, equality)
    # The body identity dominates this block and its nested regions, including
    # nested loop conditions. It does not dominate this loop's own condition.
    depend_singleton_guards_on_induction!(body, MLIR.IR.result(equality, 1))
    MLIR.IR.setattr!(op, "reactant.singleton_predicate", MLIR.IR.Attribute(true))
    return true
end

function preserve_loop_limits!(
    op, guarded=false, constants=Dict{MLIR.IR.Value,Any}(); singleton_only=false
)
    guarded |= MLIR.IR.name(op) == "stablehlo.if"
    for region in op, block in region, child in collect(block)
        preserve_loop_limits!(child, guarded, constants; singleton_only)
    end
    MLIR.IR.name(op) == "stablehlo.while" || return nothing
    # Retain scalar iteration where lazy branches depend on it, while leaving
    # unconditional tensor loops available to loop raising and auto-batching.
    guarded || contains_lazy_branch(op) || return nothing
    singleton_only && !is_singleton_loop(op) && return nothing
    condition = first(first(op))
    for compare in collect(condition)
        MLIR.IR.name(compare) == "stablehlo.compare" || continue
        for i in 1:MLIR.IR.noperands(compare)
            value = MLIR.IR.operand(compare, i)
            if MLIR.IR.is_block_arg(value) && MLIR.IR.block_owner(value) == condition
                position = MLIR.IR.block_arg_num(value) + 1
                body = first(MLIR.IR.region(op, 2))
                carried = MLIR.IR.operand(MLIR.IR.terminator(body), position)
                carried == MLIR.IR.argument(body, position) || continue
                value = MLIR.IR.operand(op, position)
            end
            if singleton_only && MLIR.IR.is_op_res(value)
                owner = MLIR.IR.op_owner(value)
                if MLIR.IR.name(owner) == "stablehlo.optimization_barrier" &&
                    MLIR.IR.getattr(owner, "reactant.loop_limit") !== nothing
                    MLIR.IR.setattr!(
                        owner, "reactant.singleton_loop_limit", MLIR.IR.Attribute(true)
                    )
                    continue
                end
            end
            count = constant_loop_limit(value, constants)
            count === nothing && continue
            typemin(Int64) <= count <= typemax(Int64) || continue
            ty = MLIR.IR.type(value)
            element = eltype(ty)
            attribute = fill(MLIR.IR.Attribute(count, element), ty)
            count = Int64(count)
            # A constant defined inside the condition cannot escape its block.
            # Materialize the same scalar outside the loop before sealing it.
            copy = MLIR.IR.create_operation_common(
                "stablehlo.constant",
                MLIR.IR.location(op);
                results=[ty],
                operands=MLIR.IR.Value[],
                attributes=[MLIR.IR.NamedAttribute("value", attribute)],
                result_inference=false,
            )
            parent = MLIR.IR.block(op)
            MLIR.IR.insert_before!(parent, op, copy)
            barrier = MLIR.IR.create_operation_common(
                "stablehlo.optimization_barrier",
                MLIR.IR.location(op);
                results=[ty],
                operands=[MLIR.IR.result(copy, 1)],
                result_inference=false,
            )
            bounds = MLIR.IR.Attribute([
                MLIR.IR.Attribute([MLIR.IR.Attribute(count), MLIR.IR.Attribute(count)])
            ])
            MLIR.IR.setattr!(barrier, "enzymexla.bounds", bounds)
            MLIR.IR.setattr!(barrier, "reactant.loop_limit", MLIR.IR.Attribute(true))
            if singleton_only
                MLIR.IR.setattr!(
                    barrier, "reactant.singleton_loop_limit", MLIR.IR.Attribute(true)
                )
            end
            MLIR.IR.insert_before!(parent, op, barrier)
            MLIR.IR.setoperand!(compare, i, MLIR.IR.result(barrier, 1))
        end
    end
    return nothing
end

function expose_loop_limits_for_ad!(op; preserve_singletons=false)
    for region in op, block in region, child in collect(block)
        expose_loop_limits_for_ad!(child; preserve_singletons)
    end
    MLIR.IR.name(op) == "stablehlo.optimization_barrier" || return nothing
    MLIR.IR.getattr(op, "reactant.loop_limit") === nothing && return nothing
    if preserve_singletons &&
        MLIR.IR.getattr(op, "reactant.singleton_loop_limit") !== nothing
        return nothing
    end
    MLIR.API.mlirValueReplaceAllUsesOfWith(MLIR.IR.result(op, 1), MLIR.IR.operand(op, 1))
    MLIR.IR.rmfromparent!(op)
    MLIR.IR.dispose(op)
    return nothing
end

function run_pass_pipeline!(mod, pass_pipeline, key=""; enable_verifier=true)
    pm = MLIR.IR.PassManager()
    id = nothing
    try
        MLIR.API.mlirPassManagerEnableXLATraceTiming(pm)
        MLIR.IR.enable_verifier!(pm, enable_verifier)
        opm = MLIR.IR.OpPassManager(pm)
        MLIR.IR.add_pipeline!(opm, pass_pipeline)
        id = Reactant.Profiler.profiler_activity_start(
            "run_pass_pipeline! $key", Reactant.Profiler.TRACE_ME_LEVEL_CRITICAL
        )
        run!(pm, MLIR.IR.Operation(mod), key)
    finally
        !isnothing(id) && Reactant.Profiler.profiler_activity_end(id)
        MLIR.IR.dispose(pm)
    end
    return mod
end

# Seal branch results only after differentiation and MLIR optimization. XLA
# otherwise speculates cheap pure operations from both arms of a conditional.
# Keeping this out of the differentiable IR requires no barrier adjoint.
function preserve_lazy_branch_returns!(op)
    for region in op, block in region
        for child in collect(block)
            preserve_lazy_branch_returns!(child)
        end
        MLIR.IR.name(op) == "stablehlo.if" || continue
        terminator = MLIR.IR.terminator(block)
        operands = MLIR.IR.operands(terminator)
        isempty(operands) && continue
        barrier = MLIR.IR.create_operation_common(
            "stablehlo.optimization_barrier",
            MLIR.IR.Location();
            results=MLIR.IR.type.(operands),
            operands,
            result_inference=false,
        )
        MLIR.IR.insert_before!(block, terminator, barrier)
        for i in eachindex(operands)
            MLIR.IR.setoperand!(terminator, i, MLIR.IR.result(barrier, i))
        end
    end
    return nothing
end

function contains_lazy_loop(op, guarded=false)
    guarded |= MLIR.IR.name(op) == "stablehlo.if"
    if MLIR.IR.name(op) == "stablehlo.while" && (guarded || contains_lazy_branch(op))
        return true
    end
    for region in op, block in region, child in block
        contains_lazy_loop(child, guarded) && return true
    end
    return false
end

# The builder owns the generated pattern lists and leaves any user-supplied
# pipeline fragments untouched. Unconditional loops keep their original phase
# order. Guarded loops expose static bounds to general cleanup, including the
# copy simplifications needed for linear-cost reverse buffer updates.
function run_lazy_loop_pipeline!(mod, builder, key)
    op = MLIR.IR.Operation(mod)
    contains_lazy_loop(op) || return run_pass_pipeline!(mod, builder(nothing), key)
    deferred = String[]
    general = builder(deferred)
    # Canonicalization alone can inline a singleton loop. Keeping only that
    # bound opaque cannot introduce copies repeated a data-dependent number
    # of times; larger bounds remain static during general optimization.
    preserve_loop_limits!(op; singleton_only=true)
    run_pass_pipeline!(mod, general, key * "_general")
    isempty(deferred) && return mod
    preserve_loop_limits!(op)
    selected = join(unique(deferred), ';')
    rewrites =
        "enzyme-hlo-generate-td{patterns=" *
        selected *
        "},transform-interpreter,enzyme-hlo-remove-transform"
    run_pass_pipeline!(mod, rewrites, key * "_loop_rewrites")
    expose_loop_limits_for_ad!(op; preserve_singletons=true)
    run_pass_pipeline!(mod, general, key * "_static_cleanup")
    return mod
end

# The standard compiler supplies these phase boundaries explicitly. Keep the
# low-level runner opaque: nested or quoted custom pass pipelines are MLIR's
# syntax, and must reach its parser unchanged.
function run_default_compiler_pipeline!(mod, before_batch, before_ad, after_ad, key)
    preserve_singleton_loop_predicates!(MLIR.IR.Operation(mod))
    preserve_loop_limits!(MLIR.IR.Operation(mod))
    run_pass_pipeline!(mod, before_batch, key * "_batch")
    preserve_loop_limits!(MLIR.IR.Operation(mod))
    if before_ad isa AbstractString
        isempty(before_ad) || run_pass_pipeline!(mod, before_ad, key * "_before_ad")
    else
        before_ad(mod, key * "_before_ad")
    end
    expose_loop_limits_for_ad!(MLIR.IR.Operation(mod))
    run_pass_pipeline!(mod, enzyme_pass, key * "_ad")
    after_ad(mod, key * "_after_ad")
    return mod
end

function run_pass_pipeline!(
    mod, propagation_options::ShardyPropagationOptions; enable_verifier=true
)
    MLIR.IR.@dispose pm = MLIR.IR.PassManager() begin
        MLIR.IR.enable_verifier!(pm, enable_verifier)
        opm = MLIR.IR.OpPassManager(pm)
        MLIR.API.addSdyPropagationPipeline(
            opm,
            propagation_options.keep_sharding_rules,
            propagation_options.conservative_propagation,
            propagation_options.debug_sharding_origins,
            propagation_options.debug_propagation_edge_sharding,
            propagation_options.skip_convert_to_reshard,
            propagation_options.skip_inline,
            propagation_options.enable_insert_explicit_collectives,
        )
        run!(pm, mod, "sdy_prop")
    end
    return mod
end

function create_pass_failure_zip(f, args)
    try
        # Create a temporary directory for the files
        temp_dir = mktempdir(; prefix="reactant_failure_", cleanup=false)

        function_name = string(f)
        function_name = replace(function_name, "!" => "_")
        Reactant.Serialization.export_to_reactant_script(
            f,
            args...;
            function_name,
            output_dir=temp_dir,
            compile_options=Reactant.CompileOptions(; optimization_passes=:none),
            try_zip_on_failure=false,
        )

        # Create the zip file
        zip_path = temp_dir * ".zip"
        temp_files = readdir(temp_dir; join=true)
        run(pipeline(`$(p7zip()) a -tzip $zip_path $temp_files`, devnull))

        return zip_path
    catch e
        @error "Failed to create debug zip file" exception = e
        return nothing
    end
end

# helper for debug purposes: String -> Text
function run_pass_pipeline_on_source(source, pass_pipeline; enable_verifier=true)
    return MLIR.IR.@with_context Reactant.ReactantContext() begin
        mod = parse(MLIR.IR.Module, source)
        run_pass_pipeline!(mod, pass_pipeline; enable_verifier)
        MLIR.IR.verifyall(MLIR.IR.Operation(mod); debug=true)
        Text(repr(mod))
    end
end

